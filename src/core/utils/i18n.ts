/**
 * Clean helper function to safely resolve dynamic translations with fallback support
 */
export function translate(locale: Locale, path: string, replacements?: Record<string, string | number>): string {
  const segments = path.split('.');
  let current: any = TRANSLATIONS[locale] || TRANSLATIONS['en'];

  for (const seg of segments) {
    if (current && typeof current === 'object' && seg in current) {
      current = current[seg];
    } else {
      // Fallback to English if translation key is missing in active locale
      let engFallback: any = TRANSLATIONS['en'];
      for (const fSeg of segments) {
        if (engFallback && typeof engFallback === 'object' && fSeg in engFallback) {
          engFallback = engFallback[fSeg];
        } else {
          return path; // Return the key path as final fallback
        }
      }
      current = engFallback;
      break;
    }
  }

  if (typeof current !== 'string') return path;

  let result = current;
  if (replacements) {
    Object.keys(replacements).forEach(key => {
      result = result.replace(`{${key}}`, String(replacements[key]));
    });
  }

  return result;
}
